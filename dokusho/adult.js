const KEEP = /^(……)?(じゃが|そして|しかし|でも|それでも|だから|じゃから|ところが|もし|どうか|ただし|つまり|やがて|けれど|けれども|さて|では|ほう|ほっほ|いや|ああ|うむ|そう|まず|また|さらに|ただ|それに|しかも|なお)$/;
function commas(s) {
  const parts = s.split('、');
  let out = parts[0];
  for (let k = 1; k < parts.length; k++) {
    const prev = out.split(/[、。！？」』\n]|……/).pop().replace(/\*\*/g, ''), next = parts[k];
    const inBold = (out.match(/\*\*/g) || []).length % 2 === 1;          // 太字（強調・原作の言葉）の中は変えない
    const toOk = !/と$/.test(prev) || /[一-龥々ァ-ヴーん]と$/.test(prev);    // 「〜すると、」の条件の「と」は残す
    const short = !inBold && toOk && [...prev].length <= 7 && /[はがをにでもとへ]$/.test(prev) && !KEEP.test(prev) && /^(\*\*)?[一-龥々ァ-ヴー]/.test(next);
    out += (short ? '' : '、') + next;
  }
  return out;
}
/* 「」『』の中（引用・書名）は変えずに、外側だけを整える */
function outside(s, f) {
  return s.split(/(「[^」]*」|『[^』]*』)/).map((x, i) => i % 2 ? x : f(x)).join('');
}
